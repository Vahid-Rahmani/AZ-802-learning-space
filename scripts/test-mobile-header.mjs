import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';
import {mkdirSync,readFileSync,rmSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const repo=resolve(import.meta.dirname,'..');
const scratch=resolve(repo,'.tmpwork/mobile-header-test');
mkdirSync(scratch,{recursive:true});
const outfile=resolve(scratch,'bundle.mjs');
await build({stdin:{contents:'export {StudyHeader} from "./app/components/study-header";',resolveDir:repo,loader:'tsx'},outfile,bundle:true,format:'esm',platform:'neutral',jsx:'automatic',tsconfig:resolve(repo,'tsconfig.json'),external:['react','react-dom','react-dom/client','react/jsx-runtime','lucide-react'],logLevel:'warning'});
const dom=new JSDOM('<!doctype html><html><body><main class="study-app"><aside class="app-sidebar"><nav><button>Learning</button></nav></aside><div id="root"></div></main></body></html>',{url:'https://mobile.test/',pretendToBeVisual:true});
const {window}=dom;
for(const name of ['window','document','HTMLElement','Element','Node','Event','MouseEvent','KeyboardEvent']) Object.defineProperty(globalThis,name,{value:name==='window'?window:window[name],configurable:true});
Object.defineProperty(globalThis,'navigator',{value:window.navigator,configurable:true});
const listeners=new Set();
const breakpoint={matches:false,addEventListener:(_,fn)=>listeners.add(fn),removeEventListener:(_,fn)=>listeners.delete(fn)};
window.matchMedia=()=>breakpoint;
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const React=(await import('react')).default;
const {act}=await import('react');
const {createRoot}=await import('react-dom/client');
const {StudyHeader}=await import(pathToFileURL(outfile).href);
const root=createRoot(document.querySelector('#root'));
const props={title:'Long learning page title',course:'AZ-802',t:{lang:'en'},fontScale:1,onFontScale:()=>{},translationLanguage:'',onTranslationLanguage:()=>{},onAccount:()=>{}};
await act(async()=>root.render(React.createElement(StudyHeader,props)));
const menu=()=>document.querySelector('.sidebar-toggle-button');
const state=()=>document.body.dataset.sidebarState;
assert.equal(state(),'collapsed');
assert.equal(menu().getAttribute('aria-expanded'),'false');
assert.equal(document.querySelector('.app-sidebar').inert,true);
await act(async()=>menu().click());
assert.equal(state(),'open');
assert.equal(document.querySelector('.app-sidebar').inert,false);
await act(async()=>document.querySelector('.sidebar-backdrop').click());
assert.equal(state(),'collapsed');
await act(async()=>menu().click());
await act(async()=>document.querySelector('.app-sidebar nav button').click());
assert.equal(state(),'collapsed','choosing a page must close the mobile drawer');
await act(async()=>menu().click());
await act(async()=>document.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Escape',bubbles:true})));
assert.equal(state(),'collapsed');
await act(async()=>{breakpoint.matches=true;listeners.forEach(fn=>fn());});
assert.equal(state(),'open','desktop navigation must remain available');
await act(async()=>{breakpoint.matches=false;listeners.forEach(fn=>fn());});
assert.equal(state(),'collapsed','rotation back to mobile must not retain the dark backdrop');
for(const course of ['AZ-802','AZ-900','Docker','CCNA']){
 await act(async()=>root.render(React.createElement(StudyHeader,{...props,course})));
 assert.equal(document.querySelectorAll('h1').length,1);
 assert.equal(state(),'collapsed');
}
const css=readFileSync(resolve(repo,'app/mobile-layout.css'),'utf8');
assert.match(css,/flex: 1 1 0; height: 0; min-height: 0/,'fixed terminal contract missing');
assert.match(css,/min-height: 44px; font-size: 16px; touch-action: manipulation/,'phone input touch/zoom contract missing');
await act(async()=>root.unmount());
rmSync(scratch,{recursive:true,force:true});
console.log('PASS mobile header: four courses, closed on entry, backdrop/navigation/Escape close, desktop restoration and rotation. Fixed console and native input CSS contracts present.');
